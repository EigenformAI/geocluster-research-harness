#!/usr/bin/env python3
"""Locked native project preparation and create-only file transfers."""
import argparse
import fcntl
import os
from pathlib import Path
import re
import shutil
import stat
import struct
import sys
import tempfile
import uuid

import setup_transfer as transfer

BUNDLE = 'wattle-creek/v1'
BUNDLE_PATH = Path(__file__).resolve().parent / 'demo-bundles' / BUNDLE
RECEIPT_LIMIT = transfer.MAX_MANIFEST + 65536


def valid_uuid(value):
    try:
        parsed = uuid.UUID(value)
        if str(parsed) == value and parsed.version == 4:
            return value
    except (ValueError, TypeError, AttributeError):
        pass
    transfer.fail('invalid_operation', 'Operation must be a canonical UUID generated by setup')


def read_record(parent, name, maximum=RECEIPT_LIMIT):
    fd = transfer.open_child(parent, name)
    try:
        info = os.fstat(fd)
        if info.st_uid != 0 or info.st_gid != 0 or stat.S_IMODE(info.st_mode) != 0o600 or info.st_size > maximum:
            transfer.fail('unsafe_workspace', 'Private records must be bounded root-owned 0600 files', path=name)
        transfer.reject_acl(fd)
        with os.fdopen(os.dup(fd), 'rb') as stream:
            data = transfer.read_exact(stream, info.st_size)
        if transfer.snapshot(info) != transfer.snapshot(os.fstat(fd)):
            transfer.fail('unsafe_workspace', 'Private record changed while reading', path=name)
        transfer.assert_named(parent, name, fd)
        return transfer.parse_json(data, maximum)
    finally:
        os.close(fd)


def protected_directory(parent, name, *, create=False, private=False):
    if create:
        try:
            os.mkdir(name, 0o700 if private else 0o755, dir_fd=parent)
            os.fsync(parent)
        except FileExistsError:
            pass
    fd = transfer.open_child(parent, name, directory=True)
    try:
        info = os.fstat(fd)
        if info.st_uid != 0 or info.st_gid != 0 or info.st_mode & 0o022 or (private and stat.S_IMODE(info.st_mode) != 0o700):
            transfer.fail('unsafe_workspace', 'Protected directories must be root-owned and non-writable; setup directories must be 0700', path=name)
        transfer.reject_acl(fd)
        return fd
    except BaseException:
        os.close(fd)
        raise


def valid_identity(value):
    return isinstance(value, dict) and set(value) == {'device', 'inode'} and all(type(item) is int and item >= 0 for item in value.values())


def retained_identity(fd):
    # mnt_id is namespace-local: each Docker helper receives different numbers.
    # Check mount identity afresh through parent descriptors, never across runs.
    info = os.fstat(fd)
    return {'device': info.st_dev, 'inode': info.st_ino}


class Workspace:
    def __init__(self, path, *, locked):
        self.path = path
        self.handles = []
        self.root = self.keep(transfer.open_absolute(path))
        root_info = os.fstat(self.root)
        if os.geteuid() != 0:
            transfer.fail('root_required', 'Run the selected runtime helper as root')
        if root_info.st_uid != 0 or root_info.st_gid != 0 or root_info.st_mode & 0o022:
            transfer.fail('unsafe_workspace', 'Workspace root must be root-owned and non-writable')
        transfer.reject_acl(self.root)
        self.private = self.setup = self.staging = self.receipts = None
        try:
            self.private = self.keep(protected_directory(self.root, '.runtime'))
        except FileNotFoundError:
            if locked:
                transfer.fail('lock_required', 'Exec this helper through lifecycle-lock.py')
        if self.private is not None:
            self.validate_profile()
            for name in ('file-service', 'lifecycle', 'native', 'setup'):
                try:
                    fd = protected_directory(self.private, name, private=name in ('lifecycle', 'setup'))
                    os.close(fd)
                except FileNotFoundError:
                    pass
        if locked:
            self.validate_lock()

    def keep(self, fd):
        self.handles.append(fd)
        return fd

    def close(self):
        for fd in reversed(self.handles):
            os.close(fd)
        self.handles.clear()

    def validate_profile(self):
        try:
            fd = transfer.open_child(self.private, 'profile')
        except FileNotFoundError:
            if set(os.listdir(self.private)).intersection({'opencode', 'gateway', 'conversations'}):
                transfer.fail('profile_mismatch', 'Unmarked managed state cannot be initialized as native')
            return
        try:
            info = os.fstat(fd)
            if info.st_uid != 0 or info.st_mode & 0o022 or info.st_size > 64:
                transfer.fail('unsafe_workspace', 'Unsafe native profile marker')
            if os.read(fd, 65).strip() != b'native':
                transfer.fail('profile_mismatch', 'Workspace is not a native profile')
        finally:
            os.close(fd)

    def validate_lock(self):
        try:
            fd = transfer.open_child(self.private, 'owner.lock')
            try:
                info = os.fstat(fd)
                if info.st_uid != 0 or info.st_gid != 0 or stat.S_IMODE(info.st_mode) != 0o600 or transfer.identity(fd) != transfer.identity(9):
                    transfer.fail('lock_required', 'Descriptor 9 must refer to this workspace lifecycle lock')
                transfer.reject_acl(fd)
                with open('/proc/self/fdinfo/9', encoding='ascii') as stream:
                    if not any(line.startswith('lock:') and 'FLOCK' in line and ' WRITE ' in line for line in stream):
                        transfer.fail('lock_required', 'Descriptor 9 must retain the exclusive lifecycle lock')
                # An independent open must be excluded: a merely inherited but
                # unlocked descriptor is not authority to mutate the workspace.
                try:
                    fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
                except BlockingIOError:
                    return
                fcntl.flock(fd, fcntl.LOCK_UN)
                transfer.fail('lock_required', 'Lifecycle lock is not held')
            finally:
                os.close(fd)
        except OSError as error:
            transfer.fail('lock_required', 'Exec this helper through lifecycle-lock.py: ' + str(error))

    def records(self, *, create=False):
        if self.receipts is not None:
            return True
        if self.private is None:
            return False
        try:
            self.setup = self.keep(protected_directory(self.private, 'setup', create=create, private=True))
            self.staging = self.keep(protected_directory(self.setup, 'staging', create=create, private=True))
            self.receipts = self.keep(protected_directory(self.setup, 'receipts', create=create, private=True))
            return True
        except FileNotFoundError:
            if create:
                raise
            return False

    def project(self, project, expect=None):
        transfer.validate_project(project)
        try:
            fd = transfer.open_child(self.root, project, directory=True)
        except FileNotFoundError:
            if expect == 'existing':
                transfer.fail('project_missing', 'Selected project is missing', project=project)
            if expect is None:
                return None, False
            os.mkdir(project, 0o700, dir_fd=self.root)
            fd = transfer.open_child(self.root, project, directory=True)
            transfer.drop_acl(fd)
            os.fchown(fd, 999, 999)
            os.fchmod(fd, 0o2775)
            os.fsync(fd)
            os.fsync(self.root)
            created = True
        else:
            if expect == 'absent':
                os.close(fd)
                transfer.fail('project_exists', 'Selected new project already exists', project=project)
            created = False
        try:
            info = os.fstat(fd)
            if info.st_uid != 999 or info.st_gid != 999 or stat.S_IMODE(info.st_mode) not in (0o2770, 0o2775):
                transfer.fail('unsafe_project', 'Project must already have native ownership 999:999 and mode 2770 or 2775; existing permissions are never repaired', project=project)
            return self.keep(fd), created
        except BaseException:
            os.close(fd)
            raise

    def assert_project(self, project, fd):
        transfer.assert_named(self.root, project, fd)
        info = os.fstat(fd)
        if info.st_uid != 999 or info.st_gid != 999 or stat.S_IMODE(info.st_mode) not in (0o2770, 0o2775):
            transfer.fail('unsafe_project', 'Project permissions changed during the operation')

    def read_receipt(self, operation):
        valid_uuid(operation)
        if not self.records():
            transfer.fail('receipt_missing', 'No workspace receipt exists for this operation', operation=operation)
        try:
            record = read_record(self.receipts, operation + '.json')
        except FileNotFoundError:
            transfer.fail('receipt_missing', 'No workspace receipt exists for this operation', operation=operation)
        keys = {'protocol', 'operation', 'project', 'destination', 'kind', 'bundle', 'manifestHash',
                'manifest', 'projectIdentity', 'stageIdentity', 'treeIdentity', 'state'}
        if not isinstance(record, dict) or set(record) != keys or record['protocol'] != 1 or record['operation'] != operation:
            transfer.fail('invalid_receipt', 'Malformed setup receipt')
        transfer.validate_project(record['project'])
        if not valid_identity(record['projectIdentity']) or record['state'] not in ('staged', 'published', 'verified'):
            transfer.fail('invalid_receipt', 'Invalid recorded project identity or state')
        if record['kind'] == 'project':
            if record['destination'] is not None or record['state'] != 'verified' or any(record[key] is not None for key in ('bundle', 'manifestHash', 'manifest', 'stageIdentity', 'treeIdentity')):
                transfer.fail('invalid_receipt', 'Invalid empty-project receipt')
        else:
            if record['kind'] not in ('import', 'samples') or record['bundle'] != (BUNDLE if record['kind'] == 'samples' else None):
                transfer.fail('invalid_receipt', 'Unknown setup receipt kind')
            transfer.validate_destination(record['destination'])
            transfer.validate_manifest(record['manifest'])
            if not isinstance(record['manifestHash'], str) or not re.fullmatch('[0-9a-f]{64}', record['manifestHash']) or not all(valid_identity(record[key]) for key in ('stageIdentity', 'treeIdentity')):
                transfer.fail('invalid_receipt', 'Invalid recorded transfer identity')
        return record

    def all_receipts(self, project):
        if not self.records():
            return []
        records = []
        for name in sorted(os.listdir(self.receipts)):
            if name.startswith('.write-'):
                # Interrupted atomic writes are not receipts or cleanup authority.
                continue
            if not name.endswith('.json'):
                transfer.fail('invalid_receipt', 'Unknown object in protected receipts directory')
            record = self.read_receipt(name[:-5])
            if record['project'] == project:
                records.append(record)
        return records

    def save_receipt(self, record):
        self.records(create=True)
        name = valid_uuid(record['operation']) + '.json'
        try:
            self.read_receipt(record['operation'])
            existing = True
        except transfer.TransferError as error:
            if error.code != 'receipt_missing':
                raise
            existing = False
        temporary = '.write-' + str(uuid.uuid4())
        fd = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW | os.O_CLOEXEC, 0o600, dir_fd=self.receipts)
        try:
            transfer.write_all(fd, transfer.canonical_bytes(record))
            os.fsync(fd)
        finally:
            os.close(fd)
        if existing:
            os.rename(temporary, name, src_dir_fd=self.receipts, dst_dir_fd=self.receipts)
        else:
            transfer.rename_noreplace(self.receipts, temporary, self.receipts, name)
        os.fsync(self.receipts)

    def outcome(self, record, project=None):
        result = {key: record[key] for key in ('operation', 'project', 'destination', 'kind', 'bundle', 'manifestHash', 'state')}
        if project is None:
            project, _ = self.project(record['project'])
        if project is None:
            result['outcome'] = 'deleted'
            return result
        if retained_identity(project) != record['projectIdentity']:
            result['outcome'] = 'modified'
            return result
        if record['kind'] == 'project':
            result['outcome'] = 'unchanged'
            return result
        try:
            tree = transfer.open_child(project, record['destination'], directory=True)
        except FileNotFoundError:
            result['outcome'] = 'staged' if record['state'] == 'staged' else 'deleted'
            return result
        except (OSError, ValueError):
            result['outcome'] = 'modified' if record['state'] == 'verified' else 'unverified'
            return result
        try:
            if record['state'] != 'verified':
                result['outcome'] = 'unverified'
            else:
                try:
                    transfer.verify_tree(tree, record['manifest'], service_ownership=True)
                    result['outcome'] = 'unchanged' if retained_identity(tree) == record['treeIdentity'] else 'modified'
                    transfer.assert_named(project, record['destination'], tree)
                except (OSError, ValueError):
                    result['outcome'] = 'modified'
        finally:
            os.close(tree)
        return result

    def publish(self, record, project):
        if retained_identity(project) != record['projectIdentity']:
            transfer.fail('unverified_copy', 'Recorded project identity changed; keep its files and choose a new copy')
        stage = protected_directory(self.staging, record['operation'], private=True)
        try:
            if retained_identity(stage) != record['stageIdentity'] or read_record(stage, 'manifest.json', transfer.MAX_MANIFEST) != record['manifest']:
                transfer.fail('unverified_copy', 'Protected staging identity or manifest changed')
            tree = transfer.open_child(stage, 'tree', directory=True)
            try:
                transfer.verify_tree(tree, record['manifest'], service_ownership=True)
                if retained_identity(tree) != record['treeIdentity']:
                    transfer.fail('unverified_copy', 'Protected stage no longer matches its verified manifest')
                transfer.assert_named(stage, 'tree', tree)
                self.assert_project(record['project'], project)
                transfer.assert_named(self.staging, record['operation'], stage)
                transfer.rename_noreplace(stage, 'tree', project, record['destination'])
                os.fsync(project)
                os.fsync(stage)
                record['state'] = 'published'
                self.save_receipt(record)
                transfer.verify_tree(tree, record['manifest'], service_ownership=True)
                transfer.assert_named(project, record['destination'], tree)
                self.assert_project(record['project'], project)
                record['state'] = 'verified'
                self.save_receipt(record)
                return self.outcome(record, project)
            finally:
                os.close(tree)
        finally:
            os.close(stage)

    def resume(self, record, project):
        result = self.outcome(record, project)
        if result['outcome'] == 'unchanged' and record['state'] == 'verified':
            return dict(result, reused=True)
        if result['outcome'] == 'staged' and record['state'] == 'staged':
            return dict(self.publish(record, project), reused=True)
        transfer.fail('unverified_copy', 'Previous copy is edited, deleted, or not verified; keep it and choose a fresh destination', **result)

    def stage_import(self, project_name, project, destination, archive, *, expected_hash, allow_restricted, kind='import'):
        transfer.validate_destination(destination)
        self.assert_project(project_name, project)
        try:
            os.stat(destination, dir_fd=project, follow_symlinks=False)
        except FileNotFoundError:
            pass
        else:
            transfer.fail('destination_exists', 'Destination already exists; choose a fresh child name', destination=destination)
        self.records(create=True)
        operation = str(uuid.uuid4())
        os.mkdir(operation, 0o700, dir_fd=self.staging)
        stage = self.keep(protected_directory(self.staging, operation, private=True))
        source, manifest, tree_identity = transfer.extract_archive(archive, stage, 'tree', service_ownership=True,
                                                                 expected_hash=expected_hash, allow_restricted=allow_restricted)
        fd = os.open('manifest.json', os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW | os.O_CLOEXEC, 0o600, dir_fd=stage)
        try:
            transfer.write_all(fd, transfer.canonical_bytes(manifest))
            os.fsync(fd)
        finally:
            os.close(fd)
        os.fsync(stage)
        os.fsync(self.staging)
        record = {'protocol': 1, 'operation': operation, 'project': project_name, 'destination': destination,
                  'kind': kind, 'bundle': BUNDLE if kind == 'samples' else None,
                  'manifestHash': transfer.canonical_hash(source), 'manifest': manifest,
                  'projectIdentity': retained_identity(project), 'stageIdentity': retained_identity(stage),
                  'treeIdentity': {key: tree_identity[key] for key in ('device', 'inode')}, 'state': 'staged'}
        self.save_receipt(record)
        return self.publish(record, project)


def verify_bundle():
    fd = transfer.open_absolute(str(BUNDLE_PATH))
    try:
        manifest, _ = transfer.capture_fd(fd)
        provenance = transfer.open_relative(fd, 'provenance/manifest.json', directory=False)
        try:
            info = os.fstat(provenance)
            if info.st_size > transfer.MAX_MANIFEST:
                transfer.fail('invalid_bundle', 'Sample provenance exceeds its size limit')
            with os.fdopen(os.dup(provenance), 'rb') as stream:
                record = transfer.parse_json(transfer.read_exact(stream, info.st_size))
        finally:
            os.close(provenance)
        if not isinstance(record, dict) or record.get('schemaVersion') != 1 or record.get('template') != {'id': 'wattle-creek', 'version': 1}:
            transfer.fail('invalid_bundle', 'Image samples have the wrong bundle identity')
        files = {entry['path']: entry for entry in manifest['entries'] if entry['type'] == 'file' and entry['path'] != 'provenance/manifest.json'}
        hashes, members = record.get('memberHashes'), record.get('members')
        if not isinstance(hashes, dict) or not isinstance(members, list) or len(members) != len(files) or set(hashes) != set(files):
            transfer.fail('invalid_bundle', 'Image sample inventory differs from its manifest')
        seen = set()
        for member in members:
            if not isinstance(member, dict) or member.get('path') not in files or member['path'] in seen:
                transfer.fail('invalid_bundle', 'Invalid or duplicate image sample member')
            path = member['path']
            seen.add(path)
            if member.get('sha256') != files[path]['sha256'] or hashes[path] != files[path]['sha256'] or member.get('sizeBytes') != files[path]['size']:
                transfer.fail('invalid_bundle', 'Image sample bytes do not match their manifest', path=path)
        directories = {'.', 'provenance'}
        for path in files:
            while '/' in path:
                path = path.rsplit('/', 1)[0]
                directories.add(path)
        if {entry['path'] for entry in manifest['entries'] if entry['type'] == 'directory'} != directories:
            transfer.fail('invalid_bundle', 'Image sample contains undeclared directories')
        return fd, manifest
    except BaseException:
        os.close(fd)
        raise


def inspect(workspace, args):
    project, _ = workspace.project(args.project)
    receipts = workspace.all_receipts(args.project)
    outcomes = [workspace.outcome(record, project) for record in receipts]
    result = {'project': args.project, 'exists': project is not None,
              'children': sorted(os.listdir(project)) if project is not None else [],
              'samples': [record for record in outcomes if record['kind'] == 'samples'], 'operations': outcomes}
    if project is not None:
        workspace.assert_project(args.project, project)
    return result


def prepare(workspace, args):
    transfer.validate_project(args.project)
    if args.resume:
        record = workspace.read_receipt(args.resume)
        if record['project'] != args.project or (args.destination is not None and record['destination'] != args.destination) or (args.samples and record['kind'] != 'samples'):
            transfer.fail('invalid_operation', 'Resume receipt does not match the selected project or destination')
        project, _ = workspace.project(args.project)
        if project is None:
            transfer.fail('unverified_copy', 'Recorded project was deleted; never restore a previous copy', operation=args.resume)
        return workspace.resume(record, project)
    if args.destination is not None and not args.samples:
        transfer.fail('invalid_arguments', '--destination requires --samples')
    destination = transfer.validate_destination(args.destination or 'wattle-creek') if args.samples else None
    # Verified copies are repeatable even when the original approval created the
    # project. A recorded deletion never authorizes automatic sample restoration.
    if args.samples:
        matches = [record for record in workspace.all_receipts(args.project) if record['kind'] == 'samples' and record['destination'] == destination]
        if matches:
            project, _ = workspace.project(args.project)
            if project is None:
                transfer.fail('unverified_copy', 'Sample project was deleted; choose a fresh project or add nothing')
            return workspace.resume(matches[-1], project)
    project, created = workspace.project(args.project, args.expect)
    if args.samples:
        source, manifest = verify_bundle()
        try:
            with tempfile.TemporaryFile() as archive:
                transfer.build_archive_fd(source, manifest, archive)
                archive.seek(0)
                return dict(workspace.stage_import(args.project, project, destination, archive,
                                                  expected_hash=transfer.canonical_hash(manifest), allow_restricted=True, kind='samples'), created=created)
        finally:
            os.close(source)
    operation = str(uuid.uuid4())
    record = {'protocol': 1, 'operation': operation, 'project': args.project, 'destination': None,
              'kind': 'project', 'bundle': None, 'manifestHash': None, 'manifest': None,
              'projectIdentity': retained_identity(project), 'stageIdentity': None, 'treeIdentity': None, 'state': 'verified'}
    workspace.assert_project(args.project, project)
    workspace.save_receipt(record)
    return dict(workspace.outcome(record, project), created=created)


def import_frame(workspace, stream):
    length = struct.unpack('>I', transfer.read_exact(stream, 4))[0]
    if not 0 < length <= 8192:
        transfer.fail('invalid_frame', 'Import header length must be 1–8192 bytes')
    header = transfer.parse_json(transfer.read_exact(stream, length), 8192)
    keys = {'project', 'destination', 'allowRestricted', 'manifestHash', 'archiveLength', 'expect'}
    if not isinstance(header, dict) or set(header) != keys:
        transfer.fail('invalid_frame', 'Import header has unknown or missing fields')
    transfer.validate_project(header['project'])
    transfer.validate_destination(header['destination'])
    if type(header['allowRestricted']) is not bool or header['expect'] not in ('absent', 'existing') or not isinstance(header['manifestHash'], str) or not re.fullmatch('[0-9a-f]{64}', header['manifestHash']):
        transfer.fail('invalid_frame', 'Import header has invalid permission, expectation, or digest fields')
    archive_length = header['archiveLength']
    if type(archive_length) is not int or not 2048 <= archive_length <= transfer.MAX_BYTES or archive_length % 512:
        transfer.fail('invalid_frame', 'Import archive length must be a bounded, block-aligned byte count')
    # Spool the declared frame inside protected storage before creating a project.
    # No hostile length is allocated in memory and no malformed trailing frame is
    # allowed to publish data. The file has no name and cannot authorize recovery.
    workspace.records(create=True)
    with tempfile.TemporaryFile(dir='/proc/self/fd/' + str(workspace.setup)) as archive:
        remaining = archive_length
        while remaining:
            block = transfer.read_exact(stream, min(remaining, 1024 * 1024))
            transfer.write_bytes(archive, block)
            remaining -= len(block)
        if stream.read(1):
            transfer.fail('invalid_frame', 'Trailing bytes after the declared import archive')
        archive.seek(0)
        project, created = workspace.project(header['project'], header['expect'])
        return dict(workspace.stage_import(header['project'], project, header['destination'], archive,
                                          expected_hash=header['manifestHash'], allow_restricted=header['allowRestricted']), created=created)


def list_paths(workspace, args):
    project, _ = workspace.project(args.project, 'existing')
    if args.offset < 0 or not 1 <= args.limit <= 1000:
        transfer.fail('invalid_arguments', 'List requires offset >= 0 and limit 1–1000')
    # Listing validates types and identities, but does not hash potentially large
    # result files. Unsafe entries outside the page must not be silently skipped.
    paths, count = [], 0
    def visit(fd, prefix):
        nonlocal count
        before = transfer.snapshot(os.fstat(fd))
        for name in sorted(os.listdir(fd)):
            count += 1
            if count > transfer.MAX_ENTRIES:
                transfer.fail('invalid_path', 'Project exceeds the listing member limit')
            path = prefix + '/' + name if prefix else name
            transfer.validate_path(path)
            info = os.stat(name, dir_fd=fd, follow_symlinks=False)
            directory = stat.S_ISDIR(info.st_mode)
            child = transfer.open_child(fd, name, directory=directory)
            try:
                if directory:
                    paths.append(path)
                    visit(child, path)
                transfer.assert_named(fd, name, child)
            finally:
                os.close(child)
        if transfer.snapshot(os.fstat(fd)) != before:
            transfer.fail('source_changed', 'Directory changed while listing')
    visit(project, '')
    paths.sort()
    end = args.offset + args.limit
    workspace.assert_project(args.project, project)
    return {'project': args.project, 'paths': paths[args.offset:end], 'offset': args.offset, 'limit': args.limit,
            'hasMore': end < len(paths), 'nextOffset': end if end < len(paths) else None, 'total': len(paths)}


def export(workspace, args):
    project, _ = workspace.project(args.project, 'existing')
    source = transfer.open_relative(project, args.path)
    try:
        manifest, _ = transfer.capture_fd(source)
        with tempfile.TemporaryFile() as archive:
            transfer.build_archive_fd(source, manifest, archive)
            check = transfer.open_relative(project, args.path)
            try:
                if transfer.identity(check) != transfer.identity(source):
                    transfer.fail('source_changed', 'Export source path changed')
            finally:
                os.close(check)
            workspace.assert_project(args.project, project)
            archive.seek(0)
            shutil.copyfileobj(archive, sys.stdout.buffer, 1024 * 1024)
            sys.stdout.buffer.flush()
    finally:
        os.close(source)


class Parser(argparse.ArgumentParser):
    def error(self, message):
        transfer.fail('invalid_arguments', message)


def main():
    parser = Parser(description=__doc__)
    parser.add_argument('--capabilities', action='store_true')
    parser.add_argument('--workspace', default='/workspace')
    commands = parser.add_subparsers(dest='command')
    for name in ('inspect', 'prepare', 'list', 'export'):
        command = commands.add_parser(name)
        command.add_argument('--project', required=True)
        if name == 'prepare':
            command.add_argument('--expect', choices=('absent', 'existing'), required=True)
            command.add_argument('--samples', action='store_true')
            command.add_argument('--destination')
            command.add_argument('--resume')
        elif name == 'export':
            command.add_argument('--path', required=True)
        elif name == 'list':
            command.add_argument('--offset', type=int, default=0)
            command.add_argument('--limit', type=int, default=100)
    commands.add_parser('import')
    receipt = commands.add_parser('receipt')
    receipt.add_argument('--operation', required=True)
    args = parser.parse_args()
    if args.capabilities:
        if args.command:
            transfer.fail('invalid_arguments', 'Capabilities probe takes no operation')
        return {'protocol': 1, 'initialize': True, 'import': True, 'export': True, 'bundles': [BUNDLE]}
    if args.command is None:
        transfer.fail('invalid_arguments', 'Choose inspect, prepare, import, export, list, or receipt')
    if hasattr(args, 'project'):
        transfer.validate_project(args.project)
    workspace = Workspace(args.workspace, locked=args.command != 'inspect')
    try:
        if args.command == 'inspect':
            return inspect(workspace, args)
        if args.command == 'prepare':
            return prepare(workspace, args)
        if args.command == 'import':
            return import_frame(workspace, sys.stdin.buffer)
        if args.command == 'list':
            return list_paths(workspace, args)
        if args.command == 'receipt':
            return workspace.outcome(workspace.read_receipt(args.operation))
        export(workspace, args)
        return None
    finally:
        workspace.close()


if __name__ == '__main__':
    try:
        result = main()
        if result is not None:
            print(transfer.canonical_bytes(result).decode('utf-8'))
    except (ValueError, OSError, UnicodeError, RecursionError) as error:
        code = getattr(error, 'code', 'io_error' if isinstance(error, OSError) else 'invalid_request')
        details = getattr(error, 'details', {})
        print(transfer.canonical_bytes({'error': code, 'message': str(error), **details}).decode('utf-8'), file=sys.stderr)
        sys.exit(2)
